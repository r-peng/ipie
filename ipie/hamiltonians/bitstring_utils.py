def fermion_act(x,oix,typ):
    if typ=='cre':
        return _apply_creation(x,int(oix))
    elif typ=='des':
        return _apply_annihilation(x,int(oix))
    else:
        raise ValueError

def string_act(x,ops,order=-1):
    if order==-1:
        ops = ops[::-1]
    s = 1
    y = x
    for i,(oix,typ) in enumerate(ops):
        y,si = fermion_act(y,int(oix),typ)
        if y is None:
            return None,0
        s *= si
    return y,s

