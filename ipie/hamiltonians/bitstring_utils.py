def count_double_occupancy(det: int, n_sites: int) -> int:
    """
    O(#electrons) method: iterate occupied bits and accumulate compact up/dn site masks,
    then popcount their AND.
    """
    det = int(det)
    d = det & ((1 << (2 * n_sites)) - 1)

    up_comp = 0
    dn_comp = 0
    for p in _iter_set_bits(d):
        site = p >> 1          # floor(p/2)
        if (p & 1) == 0:       # even -> up
            up_comp |= 1 << site
        else:                  # odd -> down
            dn_comp |= 1 << site

    return (up_comp & dn_comp).bit_count()
